'use server';

import { prisma } from '@/lib/prisma';
import { getServerSession } from 'next-auth';
import { authOptions } from '@/lib/auth-options';
import { z } from 'zod';
import { sanitizeString } from '@/lib/sanitize';
import { checkRateLimit } from '@/lib/rate-limit';

const toolInputSchema = z.object({
  toolName: z.enum(['text-summarizer', 'idea-validator', 'resume-builder', 'ai-email-writer']),
  prompt: z.string().min(3, 'Input prompt must be at least 3 characters').max(5000, 'Input prompt cannot exceed 5000 characters'),
});

export async function useTool(rawToolName: string, rawPrompt: string) {
  const session = await getServerSession(authOptions);

  if (!session || !session.user?.email) {
    return { success: false, requireLogin: true, message: 'Please login to use this tool.' };
  }

  const validationResult = toolInputSchema.safeParse({
    toolName: rawToolName,
    prompt: rawPrompt,
  });

  if (!validationResult.success) {
    return {
      success: false,
      message: validationResult.error.issues[0]?.message || 'Invalid tool input parameter.',
    };
  }

  const { toolName, prompt } = validationResult.data;
  const cleanPrompt = sanitizeString(prompt, 5000);

  // Apply rate limiting per user (10 requests per minute)
  const rateLimit = checkRateLimit(session.user.email, {
    limit: 10,
    windowMs: 60 * 1000,
    identifier: 'tool-execution',
  });

  if (!rateLimit.success) {
    return {
      success: false,
      message: 'Rate limit exceeded. Please wait a moment before running another AI tool.',
    };
  }

  try {
    const user = await prisma.user.findUnique({
      where: { email: session.user.email },
    });

    if (!user) {
      return { success: false, requireLogin: true, message: 'User account not found.' };
    }

    // Check usage count for this specific tool
    const usageCount = await prisma.toolUsage.count({
      where: { userId: user.id, toolName: toolName },
    });

    const MAX_FREE_TRIALS_PER_TOOL = 3;

    if (usageCount >= MAX_FREE_TRIALS_PER_TOOL) {
      return {
        success: false,
        outOfCredits: true,
        message: `You have exhausted your ${MAX_FREE_TRIALS_PER_TOOL} free trials for this tool.`,
      };
    }

    // Controlled mock responses
    let result = '';
    switch (toolName) {
      case 'text-summarizer':
        result = "Summary: Key operational takeaways and highlights extracted successfully. (Generated by Moh-AI Tech)";
        break;
      case 'idea-validator':
        result = "Market Viability Report:\n\n- Feasibility Score: 88%\n- Competitive Density: Moderate\n- Strategic Recommendation: Proceed with pilot deployment.";
        break;
      case 'resume-builder':
        result = "Professional Engineering Summary:\n- Architected high-throughput AI pipelines with PyTorch and FastAPI.\n- Deployed secure, localized computer vision models on edge nodes.";
        break;
      case 'ai-email-writer':
        result = "Subject: Accelerating Operations with Moh-AI Tech\n\nDear Team,\n\nWe would welcome the opportunity to discuss how our localized AI models can eliminate quality bottlenecks on your production floor.\n\nBest regards,\nMoh-AI Tech";
        break;
    }

    // Persist tool usage in database
    await prisma.toolUsage.create({
      data: {
        userId: user.id,
        toolName: toolName,
        prompt: cleanPrompt,
        result: result,
      },
    });

    return { 
      success: true, 
      result, 
      remainingCredits: MAX_FREE_TRIALS_PER_TOOL - (usageCount + 1),
    };

  } catch (error) {
    console.error("[SECURITY LOG] Tool execution persistence failure");
    return { success: false, message: 'An internal error occurred while processing your request.' };
  }
}
